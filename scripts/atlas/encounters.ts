/**
 * Encounters-only Pokénav for the games without a decompilation (Generation 5 onward): the
 * locations and what lives in them, straight from the Pokédex files (`npm run pokedex`: PokeAPI +
 * PKHeX encounter tables). Wild, static, gift and trade encounters are all there; maps, items, NPCs,
 * shops and trainer teams aren't, because none of the pinned sources has them (docs/atlas-sources.md).
 */
import type { AtlasFile, AtlasLocation, LocationKind } from '../../src/domain/atlasTypes.ts';
import { OUT, readJSON } from './common.ts';
import { resolve } from 'node:path';

/** The parts of pokedex-<book>.json this builder reads (shape: src/domain/pokedex.ts). */
interface PokedexData {
  games: { id: string }[];
  areas: { loc: string; name: string }[];
  methods: string[];
  encounters: Record<string, [number, number, number, ...unknown[]][]>;
}

export interface LiteGame {
  /** Atlas game id (the file is atlas-<id>.json). */
  id: string;
  name: string;
  /** Pokédex file id (gen5, lgpe, …) and the Pokédex game ids whose encounters this file covers. */
  book: string;
  generation: number;
  dexGames: string[];
}

