/** A best guess from the name alone; the encounter tables don't say what kind of place it is. */
export function kindOf(name: string): LocationKind {
  const n = name.toLowerCase();
  if (/\bsea\b|ocean|\bbay\b|\blake\b|\bsurf/.test(n) && /route|sea/.test(n)) return 'sea-route';
  if (/route|road|\bpath\b|trail|\bwild area\b|\bwild zone\b|\bfield\b/.test(n)) return 'route';
  if (/\bcity\b/.test(n)) return 'city';
  if (/\btown\b|village|\bhamlet\b/.test(n)) return 'town';
  if (/cave|cavern|tunnel|mine|grotto|\bden\b|\bpit\b|\bburrow|lair/.test(n)) return 'cave';
  if (/tower|ruins|temple|castle|\bgate\b|\bvault|\bpalace|\bmansion|\bfactory|\blab|\bplant\b|\bhall\b/.test(n)) return 'dungeon';
  return 'landmark';
}

export function buildEncounters(g: LiteGame): { file: AtlasFile; gaps: string } {
  const pd = readJSON<PokedexData>(resolve(OUT, `pokedex-${g.book}.json`));
  const gameIdx = new Set(g.dexGames.map((id) => pd.games.findIndex((x) => x.id === id)));
  if (gameIdx.has(-1)) throw new Error(`${g.id}: ${g.dexGames.join(', ')} not all in pokedex-${g.book}.json`);
  const locations: Record<string, AtlasLocation> = {};
  const staticLocs = new Set<string>();
  let rows = 0;
  for (const encs of Object.values(pd.encounters))
    for (const [game, area, method] of encs) {
      if (!gameIdx.has(game)) continue;
      rows++;
      const a = pd.areas[area];
      locations[a.loc] ??= {
        id: a.loc, name: a.name, kind: kindOf(a.name), maps: [], connections: [], pokecenter: false, shops: [], obstacles: [], items: [], npcs: [], trainers: [], events: [],
      };
      if (/static|gift|trade/i.test(pd.methods[method])) staticLocs.add(a.loc);
    }
  const file: AtlasFile = {
    version: 1,
    game: g.id,
    name: g.name,
    generation: g.generation,
    source: { repo: 'PokeAPI + PKHeX encounter tables (via the Pokédex data)', commit: '' },
    locations,
    trainers: {},
    items: {},
    unplaced: [],
    badges: [],
    unverified: {},
  };
  const gaps = `# Pokénav data gaps — ${g.name}

Generated by \`npm run atlas\` (scripts/build-atlas.ts); do not edit. Source: the Pokédex data (PokeAPI + PKHeX encounter tables).

This game has **encounters only**: no decompilation exists to read, and none of the pinned sources lists its maps, items, NPCs, shops or trainer teams (see docs/atlas-sources.md).

| What | Found | Notes |
|---|---|---|
| Locations with encounters | ${Object.keys(locations).length} | place kind (route, city, cave…) is guessed from the name |
| Encounter rows (wild, static, gift, trade) | ${rows} | ${staticLocs.size} locations include static / gift / trade encounters |
| Map, items, NPCs, shops, gyms, trainers | 0 | not available |
`;
  return { file, gaps };
}
